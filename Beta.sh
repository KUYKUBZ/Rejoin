#!/data/data/com.termux/files/usr/bin/bash
# ================================================================
# beta.sh — Auto-install + Auto-rejoin for Delta/Roblox
# Usage:
#   ./beta.sh                  # auto ทุกอย่าง
#   ./beta.sh --place 920587237
#   ./beta.sh --package com.roblox.client
#   ./beta.sh --no-rejoin      # ติดตั้งอย่างเดียว ไม่ monitor
#   ./beta.sh --status         # ดูสถานะครั้งเดียว
#   ./beta.sh --uninstall      # ถอน writer
# ================================================================

set -u

# ---------- defaults ----------
DELTA_ROOT="${DELTA_ROOT:-/storage/emulated/0/Delta}"
WRITER_NAME="zz_roblox_status.lua"
ALIVE_WINDOW=10          # heartbeat ต้องสดภายในกี่วินาที
POLL_INTERVAL=5          # เช็คทุกกี่วินาที
PLACE_ID=""
TARGET_PKG=""
MODE="auto"              # auto | install-only | status | uninstall

CYAN='\033[1;36m'; GREEN='\033[1;32m'
YELLOW='\033[1;33m'; RED='\033[1;31m'; RESET='\033[0m'

# ---------- parse args ----------
while [ $# -gt 0 ]; do
    case "$1" in
        --place)     PLACE_ID="$2"; shift 2 ;;
        --package)   TARGET_PKG="$2"; shift 2 ;;
        --no-rejoin) MODE="install-only"; shift ;;
        --status)    MODE="status"; shift ;;
        --uninstall) MODE="uninstall"; shift ;;
        -h|--help)
            grep '^# ' "$0" | sed 's/^# //'
            exit 0 ;;
        *) echo "unknown arg: $1"; exit 2 ;;
    esac
done

# ---------- logger ----------
log()  { printf '[%s] %b\n' "$(date +%T)" "$*"; }
ok()   { printf "${GREEN}✔${RESET} %b\n" "$*"; }
err()  { printf "${RED}✘${RESET} %b\n" "$*"; }
warn() { printf "${YELLOW}⚠${RESET} %b\n" "$*"; }

# ---------- 1. permission check ----------
ensure_storage() {
    if [ -d "/storage/emulated/0" ] && ls /storage/emulated/0 >/dev/null 2>&1; then
        return 0
    fi
    err "ไม่มีสิทธิ์เข้าถึง /storage/emulated/0"
    warn "กำลังขอสิทธิ์..."
    command -v termux-setup-storage >/dev/null 2>&1 \
        && termux-setup-storage
    sleep 3
    if ! ls /storage/emulated/0 >/dev/null 2>&1; then
        err "ยังไม่ได้สิทธิ์ — กด Allow ตอน popup แล้วรันใหม่"
        exit 1
    fi
}

# ---------- 2. path detection ----------
find_autoexec() {
    local c
    for c in "$DELTA_ROOT/autoexec" "$DELTA_ROOT/Autoexec" \
             "$DELTA_ROOT/AutoExec" "$DELTA_ROOT/auto-exec" \
             "$DELTA_ROOT/scripts/autoexec" "$DELTA_ROOT/autoload"; do
        [ -d "$c" ] && { printf '%s' "$c"; return 0; }
    done
    # fallback: ค้นหาทั่ว Delta root
    c=$(find "$DELTA_ROOT" -maxdepth 3 -type d -iname "*autoexec*" 2>/dev/null | head -1)
    [ -n "$c" ] && { printf '%s' "$c"; return 0; }
    return 1
}

find_workspace() {
    local c
    for c in "$DELTA_ROOT/workspace" "$DELTA_ROOT/Workspace" "$DELTA_ROOT"; do
        [ -d "$c" ] && { printf '%s' "$c"; return 0; }
    done
    return 1
}

AUTOEXEC=$(find_autoexec) || {
    err "ไม่พบ autoexec folder ใน $DELTA_ROOT"
    warn "ลอง: find $DELTA_ROOT -maxdepth 3 -type d"
    exit 1
}
WORKSPACE=$(find_workspace) || WORKSPACE="$DELTA_ROOT/workspace"

# ---------- 3. Lua writer ----------
WRITER_FILE="$AUTOEXEC/$WRITER_NAME"

write_lua() {
    cat > "$WRITER_FILE" <<'LUA_EOF'
-- zz_roblox_status.lua — auto-generated by beta.sh
local Players    = game:GetService("Players")
local RunService = game:GetService("RunService")
local player = Players.LocalPlayer

local lastStatus, lastHb = nil, 0

local function safeWrite(n, d) pcall(writefile, n, d) end

local function isInGame()
    if not player then return false end
    local c = player.Character
    if not c then return false end
    return c:FindFirstChild("HumanoidRootPart") ~= nil
       and (c:FindFirstChildOfClass("Humanoid") or {Health=0}).Health > 0
end

local function tick()
    local st = isInGame() and "IN_GAME" or "NOT_IN_GAME"
    if st ~= lastStatus then
        lastStatus = st
        safeWrite("status.txt", st)
        safeWrite("info.txt", string.format(
            '{"status":"%s","placeId":%d,"player":"%s","time":%d}',
            st, game.PlaceId or 0,
            (player and player.Name) or "?", os.time()))
        pcall(print, "[status] " .. st)
    end
    local n = os.time()
    if n - lastHb >= 1 then
        lastHb = n
        safeWrite("heartbeat.txt", tostring(n))
    end
end

tick()
RunService.Heartbeat:Connect(tick)
LUA_EOF
}

install_writer() {
    if [ -f "$WRITER_FILE" ]; then
        ok "writer มีอยู่แล้ว: $WRITER_FILE"
        return 0
    fi
    write_lua
    [ -f "$WRITER_FILE" ] || { err "เขียน writer ไม่สำเร็จ"; exit 1; }
    ok "ติดตั้ง writer: $WRITER_FILE"
}

# ---------- 4. API helpers ----------
ga_status() {
    local s=""
    [ -f "$WORKSPACE/status.txt" ] && s=$(<"$WORKSPACE/status.txt" 2>/dev/null)
    case "$s" in
        IN_GAME|NOT_IN_GAME) printf '%s' "$s" ;;
        *) printf 'UNKNOWN' ;;
    esac
}

ga_in_game() { [ "$(ga_status)" = "IN_GAME" ]; }

ga_alive() {
    local ts
    [ -f "$WORKSPACE/heartbeat.txt" ] \
        && ts=$(<"$WORKSPACE/heartbeat.txt" 2>/dev/null) \
        || return 1
    [[ "$ts" =~ ^[0-9]+$ ]] || return 1
    local d=$(( $(date +%s) - ts ))
    [ "$d" -lt "$ALIVE_WINDOW" ] && [ "$d" -ge -5 ]
}

# ---------- 5. open Roblox ----------
open_roblox() {
    local pkg="${TARGET_PKG:-com.roblox.client}"
    local url=""
    [ -n "$PLACE_ID" ] && url="roblox://experiences/start?placeId=$PLACE_ID"

    if [ -n "$url" ]; then
        am start -a android.intent.action.VIEW -d "$url" -p "$pkg" >/dev/null 2>&1 \
            || am start -a android.intent.action.VIEW -d "$url" >/dev/null 2>&1
    else
        am start -a android.intent.action.MAIN \
            -c android.intent.category.LAUNCHER -p "$pkg" >/dev/null 2>&1 \
            || am start -a android.intent.action.MAIN \
               -c android.intent.category.LAUNCHER \
               -n "$pkg/com.roblox.client.startup.ActivitySplash" >/dev/null 2>&1
    fi
}

# ---------- 6. commands ----------
do_status() {
    printf 'Workspace: %s\n' "$WORKSPACE"
    printf 'Autoexec:  %s\n' "$AUTOEXEC"
    printf 'Status:    %s\n' "$(ga_status)"
    printf 'Alive:     %s\n' "$(ga_alive && echo yes || echo no)"
    [ -f "$WORKSPACE/info.txt" ] && printf 'Info:      %s\n' "$(<"$WORKSPACE/info.txt")"
}

do_uninstall() {
    if [ -f "$WRITER_FILE" ]; then
        rm -f "$WRITER_FILE"
        ok "ถอนแล้ว: $WRITER_FILE"
    else
        warn "ไม่พบไฟล์: $WRITER_FILE"
    fi
}

# ---------- 7. auto-rejoin loop ----------
auto_loop() {
    log "เริ่มโหมด auto-rejoin (poll=${POLL_INTERVAL}s)"
    log "package=${TARGET_PKG:-auto}  place=${PLACE_ID:-ไม่ระบุ}"
    log "หยุดด้วย Ctrl+C"

    # ถามเปิด Roblox ครั้งแรกไหม
    if ! ga_alive; then
        warn "writer ยังไม่ทำงาน — ต้องเปิด Roblox ผ่าน Delta ก่อน"
        printf "เปิด Roblox เลยไหม? [Y/n] "
        read -r ans
        case "${ans:-Y}" in
            [Yy]*|"") open_roblox; sleep 5 ;;
        esac
    fi

    local reopen_count=0
    local last_alive=0

    while true; do
        if ga_alive; then
            last_alive=$(date +%s)
            if ga_in_game; then
                # อยู่ในเกม — เงียบไว้
                :
            else
                printf '[%s] %b\n' "$(date +%T)" "${YELLOW}lobby${RESET} — รอเข้าเกม"
            fi
        else
            local now=$(date +%s)
            local dead_for=$(( now - last_alive ))
            # ปล่อยให้ตายเกิน 15 วิค่อย reopen (กัน respawn)
            if [ "$dead_for" -gt 15 ]; then
                reopen_count=$((reopen_count + 1))
                printf '[%s] %b (ครั้งที่ %d)\n' \
                    "$(date +%T)" "${RED}writer ตาย${RESET}" "$reopen_count"
                open_roblox
                sleep 20
                last_alive=$(date +%s)
            fi
        fi
        sleep "$POLL_INTERVAL"
    done
}

# ---------- main ----------
main() {
    ensure_storage

    case "$MODE" in
        status)      do_status; exit 0 ;;
        uninstall)   do_uninstall; exit 0 ;;
        install-only)
            install_writer
            ok "ติดตั้งเสร็จ — เปิด Delta เล่น Roblox ได้เลย"
            warn "อย่าลืมเปิด Auto-Execute ใน Delta Settings"
            exit 0 ;;
    esac

    # auto mode
    log "DELTA_ROOT=$DELTA_ROOT"
    log "AUTOEXEC=$AUTOEXEC"
    log "WORKSPACE=$WORKSPACE"
    install_writer

    if [ ! -f "$WORKSPACE/status.txt" ]; then
        warn "ยังไม่มี status.txt — เปิด Delta + Roblox ก่อน"
        printf "เปิด Roblox เดี๋ยวนี้เลยไหม? [Y/n] "
        read -r ans
        case "${ans:-Y}" in
            [Yy]*|"") open_roblox; sleep 10 ;;
        esac
    fi

    auto_loop
}

main
