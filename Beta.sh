#!/data/data/com.termux/files/usr/bin/bash
# ================================================================
# roblox_status.sh
# - ติดตั้ง Lua writer เข้า Delta autoexec (รันอัตโนมัติ)
# - เปิด Bash API อ่านสถานะ in-game จาก workspace
# ================================================================

set -u

# ---------- config ----------
DELTA_ROOT="${DELTA_ROOT:-/storage/emulated/0/Delta}"
GA_ALIVE_WINDOW="${GA_ALIVE_WINDOW:-10}"
WRITER_FILE="zz_roblox_status.lua"

CYAN='\033[1;36m'; GREEN='\033[1;32m'
YELLOW='\033[1;33m'; RED='\033[1;31m'; RESET='\033[0m'

# ---------- path detection ----------
detect_autoexec() {
    local c
    for c in \
        "$DELTA_ROOT/autoexec" \
        "$DELTA_ROOT/Autoexec" \
        "$DELTA_ROOT/AutoExec" \
        "$DELTA_ROOT/scripts/autoexec" \
        "$DELTA_ROOT/auto-exec" \
        "$DELTA_ROOT/autoload"; do
        [ -d "$c" ] && { echo "$c"; return 0; }
    done
    return 1
}

detect_workspace() {
    local c
    for c in \
        "$DELTA_ROOT/workspace" \
        "$DELTA_ROOT/Workspace" \
        "$DELTA_ROOT"; do
        [ -d "$c" ] && { echo "$c"; return 0; }
    done
    return 1
}

# ---------- install / uninstall ----------
install_writer() {
    if [ ! -d "/storage/emulated/0" ]; then
        echo -e "${RED}ไม่มีสิทธิ์เข้าถึง storage${RESET}"
        echo "รันก่อน: termux-setup-storage"
        return 1
    fi

    local ae ws
    ae=$(detect_autoexec) || {
        echo -e "${RED}ไม่พบ autoexec folder ของ Delta${RESET}"
        echo "ลองหาดูเองด้วย: find $DELTA_ROOT -maxdepth 2 -type d"
        return 1
    }
    ws=$(detect_workspace) || ws="$DELTA_ROOT/workspace"

    echo -e "${CYAN}Autoexec:${RESET}  $ae"
    echo -e "${CYAN}Workspace:${RESET} $ws"

    cat > "$ae/$WRITER_FILE" <<'LUA_EOF'
-- zz_roblox_status.lua
-- Auto-generated by roblox_status.sh — อย่าแก้ด้วยมือ
local Players    = game:GetService("Players")
local RunService = game:GetService("RunService")
local player = Players.LocalPlayer

local STATUS_FILE    = "status.txt"
local HEARTBEAT_FILE = "heartbeat.txt"
local INFO_FILE      = "info.txt"
local HB_INTERVAL    = 1

local lastStatus, lastHb = nil, 0

local function safeWrite(name, data)
    pcall(writefile, name, data)
end

local function isInGame()
    if not player then return false end
    local char = player.Character
    if not char then return false end
    local hrp = char:FindFirstChild("HumanoidRootPart")
    local hum = char:FindFirstChildOfClass("Humanoid")
    return hrp ~= nil and hum ~= nil and hum.Health > 0
end

local function tick()
    local st = isInGame() and "IN_GAME" or "NOT_IN_GAME"
    if st ~= lastStatus then
        lastStatus = st
        safeWrite(STATUS_FILE, st)
        safeWrite(INFO_FILE, string.format(
            '{"status":"%s","placeId":%d,"player":"%s","time":%d}',
            st, game.PlaceId or 0,
            (player and player.Name) or "?", os.time()))
        pcall(function() print("[status] " .. st) end)
    end
    local now = os.time()
    if now - lastHb >= HB_INTERVAL then
        lastHb = now
        safeWrite(HEARTBEAT_FILE, tostring(now))
    end
end

tick()
RunService.Heartbeat:Connect(tick)
LUA_EOF

    echo -e "${GREEN}ติดตั้งสำเร็จ:${RESET} $ae/$WRITER_FILE"
    echo "Writer จะรันอัตโนมัติทุกครั้งที่ Delta โหลด Roblox"
    echo -e "${YELLOW}อย่าลืม:${RESET} เปิด Auto-Execute ใน Delta Settings"
    return 0
}

uninstall_writer() {
    local ae
    ae=$(detect_autoexec) || { echo -e "${RED}ไม่พบ autoexec folder${RESET}"; return 1; }
    if [ -f "$ae/$WRITER_FILE" ]; then
        rm -f "$ae/$WRITER_FILE"
        echo -e "${GREEN}ถอนการติดตั้งแล้ว:${RESET} $ae/$WRITER_FILE"
    else
        echo "ไม่พบไฟล์ $WRITER_FILE ใน $ae"
    fi
}

# ---------- internal helpers ----------
_ga_workspace() { detect_workspace || echo "$DELTA_ROOT/workspace"; }

_ga_read() {
    local f="$1" s="" i
    for i in 1 2 3; do
        [ -f "$f" ] || return 1
        s=$(<"$f" 2>/dev/null)
        [ -n "$s" ] && break
        sleep 0.05
    done
    printf '%s' "$s"
}

# ---------- public API ----------

# echo "IN_GAME" | "NOT_IN_GAME" | "UNKNOWN"
ga_status() {
    local ws s
    ws=$(_ga_workspace)
    s=$(_ga_read "$ws/status.txt") || { echo "UNKNOWN"; return 2; }
    case "$s" in
        IN_GAME|NOT_IN_GAME) echo "$s" ;;
        *) echo "UNKNOWN"; return 3 ;;
    esac
}

# return 0 = in game
ga_is_in_game() { [ "$(ga_status)" = "IN_GAME" ]; }

# return 0 = executor ยังรันอยู่ (heartbeat สด)
ga_is_alive() {
    local ws ts now diff
    ws=$(_ga_workspace)
    ts=$(_ga_read "$ws/heartbeat.txt") || return 1
    [[ "$ts" =~ ^[0-9]+$ ]] || return 1
    now=$(date +%s)
    diff=$(( now - ts ))
    [ "$diff" -lt "$GA_ALIVE_WINDOW" ] && [ "$diff" -ge -5 ]
}

# echo JSON ของ info.txt
ga_info() {
    local ws
    ws=$(_ga_workspace)
    _ga_read "$ws/info.txt" || echo '{}'
}

# ga_wait_in_game [timeout] — return 0 = IN_GAME, 1 = timeout
ga_wait_in_game() {
    local timeout="${1:-120}" start now elapsed
    start=$(date +%s)
    while true; do
        ga_is_in_game && return 0
        now=$(date +%s)
        elapsed=$(( now - start ))
        [ "$elapsed" -ge "$timeout" ] && return 1
        sleep 1
    done
}

# ---------- CLI commands ----------
cmd_path() {
    local ae ws
    ae=$(detect_autoexec) || ae="<not found>"
    ws=$(detect_workspace) || ws="$DELTA_ROOT/workspace"
    echo "Autoexec:  $ae"
    echo "Workspace: $ws"
    echo "Writer:    $ae/$WRITER_FILE"
}

cmd_test() {
    echo "=== Path ==="
    cmd_path
    echo
    echo "=== Files ==="
    local ws f
    ws=$(_ga_workspace)
    for f in status.txt heartbeat.txt info.txt; do
        if [ -f "$ws/$f" ]; then
            printf '  %-15s %s\n' "$f" "$(<"$ws/$f")"
        else
            printf '  %-15s %s\n' "$f" "<missing>"
        fi
    done
    echo
    echo "=== API ==="
    printf '  status:    %s\n' "$(ga_status)"
    printf '  in_game:   %s\n' "$(ga_is_in_game && echo yes || echo no)"
    printf '  alive:     %s\n' "$(ga_is_alive  && echo yes || echo no)"
    printf '  info:      %s\n' "$(ga_info)"
}

cmd_watch() {
    local last=""
    while true; do
        local st alive
        st=$(ga_status)
        ga_is_alive && alive="alive" || alive="DEAD"
        if [ "$st|$alive" != "$last" ]; then
            printf '[%s] %-13s executor:%s\n' \
                "$(date +%T)" "$st" "$alive"
            last="$st|$alive"
        fi
        sleep 1
    done
}

usage() {
    cat <<EOF
roblox_status.sh — API + Delta autoexec installer

  install         ติดตั้ง writer เข้า autoexec ของ Delta
  uninstall       ถอนการติดตั้ง
  status          IN_GAME / NOT_IN_GAME / UNKNOWN
  in_game         yes / no
  alive           yes / no (writer ยังรันอยู่ไหม)
  info            JSON ของ info.txt
  path            แสดง autoexec / workspace path
  wait [N]        รอจนกว่า IN_GAME (default timeout 120)
  watch           loop แสดงสถานะทุก 1 วิ (Ctrl+C ออก)
  test            แสดงผลทุกอย่าง (ใช้ตรวจสอบ)

ใช้เป็น library:
  source ~/roblox_status.sh
  if ga_is_alive && ga_is_in_game; then ...; fi
EOF
}

# ---------- library mode ----------
if [ "${BASH_SOURCE[0]}" != "$0" ]; then
    return 0 2>/dev/null || true
fi

# ---------- CLI mode ----------
case "${1:-}" in
    install)   install_writer ;;
    uninstall) uninstall_writer ;;
    status)    ga_status ;;
    in_game)   ga_is_in_game && echo yes || echo no ;;
    alive)     ga_is_alive   && echo yes || echo no ;;
    info)      ga_info ;;
    path)      cmd_path ;;
    wait)      ga_wait_in_game "${2:-120}" \
                   && echo IN_GAME || { echo TIMEOUT; exit 1; } ;;
    watch)     cmd_watch ;;
    test)      cmd_test ;;
    ""|help|-h|--help) usage ;;
    *)         echo "unknown: $1"; echo; usage; exit 2 ;;
esac
